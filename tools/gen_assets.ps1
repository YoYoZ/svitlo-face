# Generates source/DotFont.mc (5x7 dot-matrix font) and resources/drawables/worldmap.png
# Run: powershell -NoProfile -File tools\gen_assets.ps1
$root = Split-Path $PSScriptRoot -Parent
$enc = New-Object System.Text.UTF8Encoding($false)

# ---------- font: 7 rows of 5 bits per glyph ('*' = heart) ----------
$font = [ordered]@{
'A'='01110 10001 10001 11111 10001 10001 10001'; 'B'='11110 10001 10001 11110 10001 10001 11110'
'C'='01110 10001 10000 10000 10000 10001 01110'; 'D'='11100 10010 10001 10001 10001 10010 11100'
'E'='11111 10000 10000 11110 10000 10000 11111'; 'F'='11111 10000 10000 11110 10000 10000 10000'
'G'='01110 10001 10000 10111 10001 10001 01111'; 'H'='10001 10001 10001 11111 10001 10001 10001'
'I'='01110 00100 00100 00100 00100 00100 01110'; 'J'='00111 00010 00010 00010 00010 10010 01100'
'K'='10001 10010 10100 11000 10100 10010 10001'; 'L'='10000 10000 10000 10000 10000 10000 11111'
'M'='10001 11011 10101 10101 10001 10001 10001'; 'N'='10001 10001 11001 10101 10011 10001 10001'
'O'='01110 10001 10001 10001 10001 10001 01110'; 'P'='11110 10001 10001 11110 10000 10000 10000'
'Q'='01110 10001 10001 10001 10101 10010 01101'; 'R'='11110 10001 10001 11110 10100 10010 10001'
'S'='01111 10000 10000 01110 00001 00001 11110'; 'T'='11111 00100 00100 00100 00100 00100 00100'
'U'='10001 10001 10001 10001 10001 10001 01110'; 'V'='10001 10001 10001 10001 10001 01010 00100'
'W'='10001 10001 10001 10101 10101 10101 01010'; 'X'='10001 10001 01010 00100 01010 10001 10001'
'Y'='10001 10001 10001 01010 00100 00100 00100'; 'Z'='11111 00001 00010 00100 01000 10000 11111'
'0'='01110 10001 10011 10101 11001 10001 01110'; '1'='00100 01100 00100 00100 00100 00100 01110'
'2'='01110 10001 00001 00010 00100 01000 11111'; '3'='11111 00010 00100 00010 00001 10001 01110'
'4'='00010 00110 01010 10010 11111 00010 00010'; '5'='11111 10000 11110 00001 00001 10001 01110'
'6'='00110 01000 10000 11110 10001 10001 01110'; '7'='11111 00001 00010 00100 01000 01000 01000'
'8'='01110 10001 10001 01110 10001 10001 01110'; '9'='01110 10001 10001 01111 00001 00010 01100'
'%'='11000 11001 00010 00100 01000 10011 00011'; '-'='00000 00000 00000 11111 00000 00000 00000'
':'='00000 01100 01100 00000 01100 01100 00000'; '.'='00000 00000 00000 00000 00000 01100 01100'
'+'='00000 00100 00100 11111 00100 00100 00000'; '/'='00000 00001 00010 00100 01000 10000 00000'
'!'='00100 00100 00100 00100 00100 00000 00100'; '?'='01110 10001 00001 00010 00100 00000 00100'
'*'='00000 01010 11111 11111 01110 00100 00000'; '^'='00100 01110 10101 00100 00100 00100 00000'
'_'='00000 00100 00100 00100 10101 01110 00100'; '#'='01100 10010 10010 01100 00000 00000 00000'
}
# '#' is the degree sign (kept ASCII so the .mc stays plain), '_' = down arrow, '^' = up arrow
$chars = ''; $vals = @()
foreach ($k in $font.Keys) {
    $chars += $k
    foreach ($row in $font[$k].Split(' ')) { $vals += [Convert]::ToInt32($row, 2) }
}
$mc = @"
import Toybox.Lang;

// GENERATED by tools/gen_assets.ps1 - do not edit by hand.
// 7 ints per glyph (rows top->bottom), 5 bits each, bit4 = leftmost pixel.
module DotFont {
    const CHARS = "$chars";
    const GLYPHS = [$($vals -join ',')];
}
"@
[IO.File]::WriteAllText("$root\source\DotFont.mc", $mc, $enc)
"font: $($chars.Length) glyphs"

# ---------- world map: 46x17 cells, equirectangular, lat +80..-70 ----------
$land = @(
 '8-13,15-20,30,35-37', '1-14,16-18,20,24-45', '3-10,13-14,17,22,24-39,43', '7-15,22-40',
 '7-13,21-22,24-28,30-38,40', '8-12,21-38,40', '9-10,12-13,20-38', '11-12,20-29,32-33,35-36,38',
 '13-16,22-28,35,37-38', '12-18,24-27,35-42', '13-18,24-27,29,39-41', '14-17,24-27,29,37-42',
 '14-16,25-26,37-42', '13-14,40-41,45', '13-14,44', '', '')
Add-Type -AssemblyName System.Drawing
$S = 2; $bmp = [System.Drawing.Bitmap]::new(46 * $S, 17 * $S)
$g = [System.Drawing.Graphics]::FromImage($bmp); $g.Clear([System.Drawing.Color]::Black)
$txt = @()
for ($r = 0; $r -lt 17; $r++) {
    $line = ('.' * 46).ToCharArray()
    foreach ($part in ($land[$r].Split(',') | Where-Object { $_ })) {
        $a, $b = $part.Split('-'); if (-not $b) { $b = $a }
        for ($c = [int]$a; $c -le [int]$b; $c++) { $line[$c] = '#'; $g.FillRectangle([System.Drawing.Brushes]::White, $c * $S, $r * $S, $S, $S) }
    }
    $txt += -join $line
}
$bmp.Save("$root\resources\drawables\worldmap.png", [System.Drawing.Imaging.ImageFormat]::Png)
$g.Dispose(); $bmp.Dispose()
$txt
